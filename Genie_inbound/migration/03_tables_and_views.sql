-- ----------------------------------------------------------------------------
-- Table: inbound.predefined_email_templates
-- Description: System-wide predefined email templates seeded by platform admin.
--              Used in the Email Template Library and Clone Templates features.
--              Seeding is handled in: 05_predefined_templates.sql
--              Run-once seed: migration/temp_querytoupdateindb/predefined_email_templates.sql
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS inbound.predefined_email_templates (
    "id" UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    "category" VARCHAR(255) NOT NULL,
    "name" VARCHAR(255) NOT NULL,
    "subject" TEXT NOT NULL,
    "body" TEXT NOT NULL,
    "description" TEXT,
    "trigger" TEXT,
    "design_style" VARCHAR(50) DEFAULT 'modern',
    "accent_color" VARCHAR(50) DEFAULT '#4F46E5',
    "created_at" TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    "updated_at" TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE OR REPLACE VIEW public.predefined_email_templates AS
    SELECT * FROM inbound.predefined_email_templates;

-- ----------------------------------------------------------------------------
-- Table: inbound.inbound_retail_agent_test_calls
-- Description: Stores logs and duration of test calls made to Retell voice agents
-- ----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS inbound.inbound_retail_agent_test_calls (
  id              uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id         uuid NOT NULL,                -- References auth.users
  agent_id        uuid NULL,                    -- Internal DB agent ID (voice_agents.id)
  retell_agent_id text NULL,                    -- Retell agent ID (e.g. agent_xxxx)
  retell_call_id  text NULL,                    -- Retell call_id returned by API
  status          text NOT NULL DEFAULT 'connected'
                  CHECK (status IN ('connected', 'completed', 'timeout', 'error')),
  duration_seconds integer NULL,                -- How long the call lasted (seconds)
  started_at      timestamp with time zone NOT NULL DEFAULT now(),
  ended_at        timestamp with time zone NULL,
  created_at      timestamp with time zone NOT NULL DEFAULT now()
);

-- Index for quick lookup by user
CREATE INDEX IF NOT EXISTS idx_retail_test_calls_user_id
  ON inbound.inbound_retail_agent_test_calls (user_id);

-- Index for quick lookup by agent
CREATE INDEX IF NOT EXISTS idx_retail_test_calls_agent_id
  ON inbound.inbound_retail_agent_test_calls (agent_id);

CREATE OR REPLACE VIEW public.inbound_retail_agent_test_calls AS
    SELECT * FROM inbound.inbound_retail_agent_test_calls;
